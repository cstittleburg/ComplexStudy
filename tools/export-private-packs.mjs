#!/usr/bin/env node
/* Turns the professor-derived content packs into SQL that stores them in the `private_packs` table for ONE
   account, so they stop being public files. Run once at pilot cutover (docs/PILOT-CUTOVER.md):

     node tools/export-private-packs.mjs owner@example.com > /tmp/private-packs.sql

   then paste the output into the Supabase SQL editor (it runs as the database owner, so row-level security does
   not block the insert). The output contains the packs' full text: do not commit it or share it.

   It loads the files exactly as the browser does (content/registry.js, frameworks.js and general.js first), and
   records what each pack file adds to each content list. */
import fs from 'fs';
import path from 'path';
import vm from 'vm';
import { fileURLToPath } from 'url';

export const PUBLIC_FILES = ['content/registry.js', 'content/frameworks.js', 'content/general.js'];
export const PRIVATE_FILES = ['content/resp.js', 'content/week1.js', 'content/pools.js', 'content/studyguide.js', 'content/community.js'];
const REGISTRIES = ['CASES', 'WHO_FIRST', 'DELEGATION', 'TREND_TEMPLATES', 'QUICKFIRE', 'RHYMES'];

export function buildPacks(root) {
  const win = {}; win.window = win; vm.createContext(win);
  const run = f => vm.runInContext(fs.readFileSync(path.join(root, f), 'utf8'), win, { filename: f });
  PUBLIC_FILES.forEach(run);
  const packs = []; const starts = {};
  for (const f of PRIVATE_FILES) {
    for (const k of REGISTRIES) starts[k] = { arr: win[k], len: win[k].length };
    run(f);
    const data = {};
    for (const k of REGISTRIES) {
      // a file may replace a list (pools.js assigns some) or append to it
      const before = starts[k]; const now = win[k];
      data[k] = now === before.arr ? now.slice(before.len) : now.slice(0);
    }
    packs.push({ pack: path.basename(f, '.js'), data });
  }
  // pools.js labels sources on earlier items after they were captured; take the final objects by identity
  const final = {}; for (const k of REGISTRIES) final[k] = new Set(win[k]);
  for (const p of packs) for (const k of REGISTRIES) p.data[k] = p.data[k].filter(x => final[k].has(x)).map(x => JSON.parse(JSON.stringify(x)));
  return packs;
}

export function toSql(packs, email) {
  const lit = s => '$pack$' + s.replace(/\$pack\$/g, '') + '$pack$';
  const rows = packs.map(p => `  (${lit(p.pack)}, ${lit(JSON.stringify(p.data))}::jsonb)`).join(',\n');
  return `-- Private packs for ${email}. Generated by tools/export-private-packs.mjs. Contains course material: do not commit.
insert into public.private_packs (user_id, pack, data)
select u.id, v.pack, v.data
from auth.users u,
(values
${rows}
) as v(pack, data)
where lower(u.email) = lower(${lit(email)})
on conflict (user_id, pack) do update set data = excluded.data, updated_at = now();

-- Should report ${packs.length} rows. If it reports 0, that email has not signed in to the app yet.
select pack, jsonb_array_length(data->'QUICKFIRE') as questions from public.private_packs p join auth.users u on u.id = p.user_id where lower(u.email) = lower(${lit(email)});
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const email = process.argv[2];
  if (!email || !email.includes('@')) { console.error('usage: node tools/export-private-packs.mjs owner@example.com > private-packs.sql'); process.exit(1); }
  const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
  const packs = buildPacks(root);
  const counts = packs.map(p => p.pack + ': ' + Object.entries(p.data).filter(([, v]) => v.length).map(([k, v]) => v.length + ' ' + k).join(', ')).join('\n  ');
  console.error('Packs:\n  ' + counts);
  process.stdout.write(toSql(packs, email));
}
